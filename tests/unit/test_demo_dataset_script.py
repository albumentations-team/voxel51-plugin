from __future__ import annotations

import pytest

from scripts.create_demo_dataset import (
    DEMO_SAMPLES,
    MARKER_FILENAME,
    PNG_SIGNATURE,
    DemoDatasetError,
    delete_generated_files,
    write_demo_images,
)


@pytest.mark.unit
def test_write_demo_images_creates_deterministic_png_files(tmp_path) -> None:
    first_paths = write_demo_images(tmp_path)
    first_payloads = [path.read_bytes() for path in first_paths]

    second_paths = write_demo_images(tmp_path)
    second_payloads = [path.read_bytes() for path in second_paths]

    assert [path.name for path in first_paths] == [spec.filename for spec in DEMO_SAMPLES]
    assert first_paths == second_paths
    assert first_payloads == second_payloads
    assert all(payload.startswith(PNG_SIGNATURE) for payload in first_payloads)
    assert (tmp_path / MARKER_FILENAME).exists()


@pytest.mark.unit
def test_delete_generated_files_requires_demo_marker(tmp_path) -> None:
    unsafe_root = tmp_path / "manual-data"
    unsafe_root.mkdir()
    (unsafe_root / "keep.txt").write_text("not generated by the script", encoding="utf-8")

    try:
        delete_generated_files(unsafe_root)
    except DemoDatasetError as error:
        assert "Refusing to delete" in str(error)
    else:
        raise AssertionError("delete_generated_files should reject unmarked directories")

    assert unsafe_root.exists()
    assert (unsafe_root / "keep.txt").exists()
